#!/usr/bin/env python3
"""scripts/build_app.py — build Aria.app, a double-clickable menu-bar app.

    venv/bin/python scripts/build_app.py               # build + install to /Applications
    venv/bin/python scripts/build_app.py --login-item  # …and start Aria at login
    venv/bin/python scripts/build_app.py --no-install  # just build dist/Aria.app

The bundle is a thin launcher around THIS repo's venv: code changes take
effect on the next launch with no rebuild. Rebuild only if the repo
moves or this script changes. Because it's a real bundle with its own
identity, macOS asks for Microphone / Accessibility / Full Disk Access
as "Aria" instead of piggybacking on Terminal.

Not a distributable build — that's docs/RELEASE_CHECKLIST.md §3.
"""
from __future__ import annotations

import argparse
import os
import plistlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUNDLE_ID = "local.aria.assistant"
APP_NAME = "Aria"
VERSION = "0.5.0"

# The bundle's main executable must be a real signed binary that stays
# alive as the parent: macOS attributes permissions (TCC) to the
# responsible process, and a shell-script executable makes that Apple's
# /bin/bash — so a Full Disk Access grant to Aria.app never matched.
# Everything spawned below this stub (bash → python) counts as "Aria".
STUB_C = r"""
#include <errno.h>
#include <limits.h>
#include <mach-o/dyld.h>
#include <signal.h>
#include <spawn.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/wait.h>

extern char **environ;
static pid_t child = 0;

static void forward(int sig) { if (child > 0) kill(child, sig); }

int main(void) {
    char exe[PATH_MAX], real[PATH_MAX], script[PATH_MAX];
    uint32_t size = sizeof(exe);
    if (_NSGetExecutablePath(exe, &size) != 0 || !realpath(exe, real)) return 1;
    char *slash = strrchr(real, '/');               /* …/Contents/MacOS/Aria */
    if (!slash) return 1;
    *slash = '\0';
    snprintf(script, sizeof(script), "%s/../Resources/launcher.sh", real);

    signal(SIGTERM, forward);
    signal(SIGINT, forward);
    signal(SIGHUP, forward);
    char *args[] = {"/bin/bash", script, NULL};
    if (posix_spawn(&child, "/bin/bash", NULL, NULL, args, environ) != 0) return 1;
    int status = 0;
    while (waitpid(child, &status, 0) < 0) {
        if (errno != EINTR) return 1;
    }
    return WIFEXITED(status) ? WEXITSTATUS(status) : 1;
}
"""

LAUNCHER = r"""#!/bin/bash
# Aria.app launcher — generated by scripts/build_app.py. Rebuild if the repo moves.
REPO="__REPO__"
LOG_DIR="$HOME/.aria/logs"
LOG="$LOG_DIR/aria.log"
mkdir -p "$LOG_DIR"
if [ -f "$LOG" ] && [ "$(stat -f%z "$LOG")" -gt 5242880 ]; then mv -f "$LOG" "$LOG.1"; fi

# Every popup is also logged; ARIA_LAUNCHER_QUIET=1 logs only (used by tests).
notify() {
  echo "[launcher] $1" >> "$LOG"
  [ -n "$ARIA_LAUNCHER_QUIET" ] && return
  /usr/bin/osascript - "$1" >/dev/null 2>&1 <<'EOF'
on run argv
  display notification (item 1 of argv) with title "Aria"
end run
EOF
}

alert_failure() {
  echo "[launcher] FAILED: $1" >> "$LOG"
  [ -n "$ARIA_LAUNCHER_QUIET" ] && return
  /usr/bin/osascript - "$1" "$LOG" >/dev/null 2>&1 <<'EOF'
on run argv
  set reply to display alert "Aria stopped" message (item 1 of argv) as critical buttons {"Open Log", "OK"} default button "OK"
  if button returned of reply is "Open Log" then do shell script "open -a Console " & quoted form of (item 2 of argv)
end run
EOF
}

need_access() {
  echo "[launcher] FAILED: no read access to $REPO (protected folder)" >> "$LOG"
  [ -n "$ARIA_LAUNCHER_QUIET" ] && return
  /usr/bin/osascript - "$REPO" >/dev/null 2>&1 <<'EOF'
on run argv
  set reply to display alert "Aria can't read its own code" message "The Aria repo is in a folder macOS protects (" & (item 1 of argv) & ").

Open Full Disk Access, click +, choose Aria from Applications, switch it on, then launch Aria again. (Aria needs this for iMessage too.)" buttons {"Open Settings", "Cancel"} default button "Open Settings"
  if button returned of reply is "Open Settings" then do shell script "open 'x-apple.systempreferences:com.apple.preference.security?Privacy_AllFiles'"
end run
EOF
}

if [ ! -x "$REPO/venv/bin/python" ]; then
  alert_failure "No Python venv found at $REPO/venv. Rebuild Aria.app from the Aria repo: venv/bin/python scripts/build_app.py"
  exit 1
fi

# ~/Documents, ~/Desktop etc. are privacy-protected: stat works without
# permission but reading doesn't, so Python would die in site.py. Check first.
if ! head -c 1 "$REPO/venv/pyvenv.cfg" >/dev/null 2>&1; then
  need_access
  exit 1
fi

# Finder-launched apps get a bare environment — restore what Aria needs.
export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"   # yt-dlp, ffplay, ffmpeg
export LANG="${LANG:-en_US.UTF-8}"
export PYTHONUNBUFFERED=1 PYTHONIOENCODING=utf-8
export KMP_DUPLICATE_LIB_OK=TRUE OMP_NUM_THREADS=1 OBJC_DISABLE_INITIALIZE_FORK_SAFETY=YES
export ARIA_APP_BUNDLE=1
cd "$REPO" || exit 1

echo "=== Aria.app launch $(date '+%Y-%m-%d %H:%M:%S') ===" >> "$LOG"
notify "Starting up — ◉ appears in the menu bar when I'm ready."

"$REPO/venv/bin/python" main.py >> "$LOG" 2>&1 &
child=$!
trap 'kill -TERM "$child" 2>/dev/null' TERM INT HUP
wait "$child"; status=$?
# a trapped signal interrupts wait — keep waiting for the real exit
while kill -0 "$child" 2>/dev/null; do wait "$child"; status=$?; done

case "$status" in
  0|130|143) ;;                                   # quit from the menu, or logout
  3) notify "Aria is already running — look for ◉ in the menu bar." ;;
  *) alert_failure "Exit code $status. Last lines of the log:
$(tail -n 8 "$LOG")" ;;
esac
exit 0
"""


def info_plist() -> dict:
    return {
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": APP_NAME,
        "CFBundleIconFile": APP_NAME,
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": VERSION,
        "CFBundleVersion": VERSION,
        "LSMinimumSystemVersion": "12.0",
        "LSUIElement": True,  # menu-bar only: no Dock icon, no app switcher entry
        "NSHighResolutionCapable": True,
        # Without these keys macOS silently denies the permission instead of asking.
        "NSMicrophoneUsageDescription":
            "Aria listens for your voice commands and the wake word. Audio is transcribed on this Mac.",
        "NSAppleEventsUsageDescription":
            "Aria controls apps like Messages, Music and Finder when you ask it to.",
        "NSDocumentsFolderUsageDescription":
            "Aria's code and settings live in your Documents folder.",
        "NSSpeechRecognitionUsageDescription":
            "Aria transcribes your voice commands.",
    }


def make_icon(dest_icns: Path) -> None:
    """Draw the app icon (indigo→violet squircle, white voice waveform) as .icns."""
    from PIL import Image, ImageDraw

    size = 1024
    top, bottom = (79, 70, 229), (147, 51, 234)
    gradient = Image.new("RGB", (size, size))
    draw = ImageDraw.Draw(gradient)
    for y in range(size):
        t = y / (size - 1)
        draw.line([(0, y), (size, y)],
                  fill=tuple(int(a + (b - a) * t) for a, b in zip(top, bottom)))

    mask = Image.new("L", (size, size), 0)
    inset = 100  # Apple's icon grid leaves a margin around the squircle
    ImageDraw.Draw(mask).rounded_rectangle(
        [inset, inset, size - inset, size - inset], radius=185, fill=255)
    icon = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    icon.paste(gradient, (0, 0), mask)

    bars = ImageDraw.Draw(icon)
    heights = [150, 300, 470, 360, 470, 300, 150]
    bar_w, gap = 56, 34
    x = (size - (len(heights) * bar_w + (len(heights) - 1) * gap)) // 2
    for h in heights:
        bars.rounded_rectangle([x, (size - h) // 2, x + bar_w, (size + h) // 2],
                               radius=bar_w // 2, fill=(255, 255, 255, 255))
        x += bar_w + gap

    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / f"{APP_NAME}.iconset"
        iconset.mkdir()
        for px in (16, 32, 128, 256, 512):
            icon.resize((px, px), Image.LANCZOS).save(iconset / f"icon_{px}x{px}.png")
            icon.resize((px * 2, px * 2), Image.LANCZOS).save(iconset / f"icon_{px}x{px}@2x.png")
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(dest_icns)], check=True)


def compile_stub(dest: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "stub.c"
        src.write_text(STUB_C)
        result = subprocess.run(["clang", "-O2", "-mmacosx-version-min=12.0",
                                 "-o", str(dest), str(src)], capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit("Couldn't compile the app launcher (needs Xcode Command Line "
                         f"Tools: xcode-select --install):\n{result.stderr}")


def build(out_dir: Path, repo: Path = ROOT) -> Path:
    app = out_dir / f"{APP_NAME}.app"
    if app.exists():
        shutil.rmtree(app)
    macos = app / "Contents" / "MacOS"
    resources = app / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    with open(app / "Contents" / "Info.plist", "wb") as fh:
        plistlib.dump(info_plist(), fh)
    launcher = resources / "launcher.sh"
    launcher.write_text(LAUNCHER.replace("__REPO__", str(repo)))
    launcher.chmod(0o755)
    compile_stub(macos / APP_NAME)
    make_icon(resources / f"{APP_NAME}.icns")

    # Ad-hoc signature: gives the bundle a stable identity so permission
    # grants stick across launches (they reset only if the bundle changes).
    subprocess.run(["codesign", "--force", "--deep", "--sign", "-", str(app)],
                   check=True, capture_output=True)
    return app


def install(app: Path, dest_dir: Path) -> Path:
    """Copy into dest_dir, replacing only a previous Aria.app built by this script."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    target = dest_dir / app.name
    if target.exists():
        try:
            with open(target / "Contents" / "Info.plist", "rb") as fh:
                existing_id = plistlib.load(fh).get("CFBundleIdentifier")
        except Exception:
            existing_id = None
        if existing_id != BUNDLE_ID:
            raise SystemExit(f"{target} exists and isn't this Aria build "
                             f"(bundle id {existing_id!r}) — not overwriting it.")
        shutil.rmtree(target)
    shutil.copytree(app, target, symlinks=True)
    # Make Launchpad / Spotlight pick up the new icon right away.
    subprocess.run(["touch", str(target)], check=False)
    return target


def add_login_item(app_path: Path) -> str:
    script = (
        'tell application "System Events"\n'
        f'  if not (exists login item "{APP_NAME}") then\n'
        f'    make login item at end with properties {{path:"{app_path}", hidden:true}}\n'
        "  end if\n"
        "end tell"
    )
    result = subprocess.run(["osascript", "-e", script], capture_output=True, text=True)
    if result.returncode != 0:
        return f"Couldn't add login item: {result.stderr.strip()}"
    return "Added to Login Items — Aria starts when you log in."


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build Aria.app (menu-bar launcher).")
    parser.add_argument("--no-install", action="store_true", help="only build dist/Aria.app")
    parser.add_argument("--dest", type=Path, default=None,
                        help="install folder (default /Applications, else ~/Applications)")
    parser.add_argument("--login-item", action="store_true", help="start Aria at login")
    args = parser.parse_args(argv)

    if not (ROOT / "venv" / "bin" / "python").exists():
        print(f"No venv at {ROOT / 'venv'} — create it first (see .claude/scripts.md).")
        return 1

    app = build(ROOT / "dist")
    print(f"Built {app}")
    if args.no_install:
        return 0

    dest = args.dest or (Path("/Applications") if os.access("/Applications", os.W_OK)
                         else Path.home() / "Applications")
    target = install(app, dest)
    print(f"Installed {target}")
    if args.login_item:
        print(add_login_item(target))
    print("Launch it from Spotlight (⌘ Space → Aria) or: open " + str(target))
    print("First launch: allow Microphone + Accessibility for Aria when macOS asks.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
